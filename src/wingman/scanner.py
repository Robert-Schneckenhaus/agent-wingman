"""Finds the source files of a repository that should be indexed."""

from __future__ import annotations

import os
import re
import subprocess
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

import pathspec

from wingman import git
from wingman.extract import spec_for

IGNORE_FILE = ".wingmanignore"
MAX_FILE_BYTES = 1_000_000

DEFAULT_EXCLUDES = [
    ".git/",
    "node_modules/",
    "bower_components/",
    "bin/",
    "obj/",
    "dist/",
    "build/",
    "out/",
    "coverage/",
    ".next/",
    ".angular/",
    "packages/*/node_modules/",
    "*.min.js",
]

_TEST_PATH = re.compile(
    r"(^|/)(tests?|__tests__|spec|specs|[^/]*\.Tests?|[^/]*\.UnitTests|[^/]*\.IntegrationTests)/"
    r"|\.(test|spec)\.[cm]?tsx?$"
    r"|Tests?\.cs$",
    re.IGNORECASE,
)
_GENERATED_NAME = re.compile(
    r"(\.g\.cs|\.g\.i\.cs|\.designer\.cs|AssemblyInfo\.cs|\.generated\.tsx?|\.gen\.tsx?)$",
    re.IGNORECASE,
)
_GENERATED_MARKER = re.compile(rb"<auto-generated|@generated|DO NOT EDIT", re.IGNORECASE)


@dataclass(frozen=True)
class SourceFile:
    path: str
    """POSIX path relative to the repository root."""
    abs_path: Path
    language: str


def is_test_path(path: str) -> bool:
    return bool(_TEST_PATH.search(path))


def is_generated(path: str, head: bytes) -> bool:
    return bool(_GENERATED_NAME.search(path) or _GENERATED_MARKER.search(head[:600]))


def _load_ignore(root: Path) -> pathspec.GitIgnoreSpec:
    patterns = list(DEFAULT_EXCLUDES)
    ignore_file = root / IGNORE_FILE
    if ignore_file.is_file():
        patterns += ignore_file.read_text(encoding="utf-8").splitlines()
    return pathspec.GitIgnoreSpec.from_lines(patterns)


def _git_files(root: Path) -> list[str] | None:
    if git.toplevel(root) is None:
        return None
    try:
        result = subprocess.run(
            [
                "git",
                "-C",
                str(root),
                "ls-files",
                "-z",
                "--cached",
                "--others",
                "--exclude-standard",
                "--",
                ".",
            ],
            capture_output=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return [p for p in result.stdout.decode("utf-8", errors="replace").split("\0") if p]


def _walk_files(root: Path, ignore: pathspec.GitIgnoreSpec) -> Iterator[str]:
    for directory, dirnames, filenames in os.walk(root):
        rel_dir = Path(directory).relative_to(root).as_posix()
        prefix = "" if rel_dir == "." else rel_dir + "/"
        dirnames[:] = sorted(d for d in dirnames if not ignore.match_file(f"{prefix}{d}/"))
        for name in filenames:
            yield prefix + name


def _git_ignored(root: Path, paths: list[str]) -> set[str]:
    if not paths or git.toplevel(root) is None:
        return set()
    try:
        result = subprocess.run(
            ["git", "-C", str(root), "check-ignore", "--stdin", "-z"],
            input="\0".join(paths).encode(),
            capture_output=True,
            check=False,
        )
    except OSError:
        return set()
    return {p for p in result.stdout.decode("utf-8", errors="replace").split("\0") if p}


def _source(root: Path, rel: str, ignore: pathspec.GitIgnoreSpec) -> SourceFile | None:
    spec = spec_for(rel)
    if spec is None or ignore.match_file(rel):
        return None
    abs_path = root / rel
    try:
        size = abs_path.stat().st_size
    except OSError:  # deleted but still tracked, broken symlink, ...
        return None
    if size > MAX_FILE_BYTES or not abs_path.is_file():
        return None
    return SourceFile(rel, abs_path, spec.name)


def scan_paths(root: Path, paths: list[str]) -> list[SourceFile]:
    """Like ``scan`` but only for the given repository-relative paths."""
    root = root.resolve()
    ignore = _load_ignore(root)
    normalized = sorted({Path(p).as_posix().removeprefix("./") for p in paths})
    git_ignored = _git_ignored(root, normalized)
    found = (_source(root, rel, ignore) for rel in normalized if rel not in git_ignored)
    return [f for f in found if f is not None]


def scan(root: Path) -> list[SourceFile]:
    """Return indexable source files below ``root``, sorted by path."""
    root = root.resolve()
    ignore = _load_ignore(root)
    candidates = _git_files(root)
    if candidates is None:
        candidates = list(_walk_files(root, ignore))

    found = (_source(root, rel, ignore) for rel in candidates)
    return sorted((f for f in found if f is not None), key=lambda f: f.path)
