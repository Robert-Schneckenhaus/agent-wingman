import subprocess
from pathlib import Path

from wingman.scanner import is_generated, is_test_path, scan

FIXTURES = Path(__file__).parent / "fixtures"


def test_scan_fixture_excludes_dependencies_and_build_output():
    ts = [f.path for f in scan(FIXTURES / "ts_app")]
    assert "node_modules/lib/index.ts" not in ts
    assert "src/billing/tax.ts" in ts
    assert "src/ui/InvoiceView.tsx" in ts

    cs = [f.path for f in scan(FIXTURES / "cs_app")]
    assert "obj/Generated.g.cs" not in cs
    assert "Billing/TaxCalculator.cs" in cs


def test_wingmanignore(tmp_path):
    (tmp_path / "keep.ts").write_text("export const a = 1;")
    (tmp_path / "legacy").mkdir()
    (tmp_path / "legacy" / "old.ts").write_text("export const b = 1;")
    (tmp_path / ".wingmanignore").write_text("legacy/\n")
    assert [f.path for f in scan(tmp_path)] == ["keep.ts"]


def test_git_repo_respects_gitignore(tmp_path):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    (tmp_path / ".gitignore").write_text("generated/\n")
    (tmp_path / "generated").mkdir()
    (tmp_path / "generated" / "api.ts").write_text("export const x = 1;")
    (tmp_path / "src").mkdir()
    (tmp_path / "src" / "app.ts").write_text("export const y = 1;")  # untracked but not ignored
    (tmp_path / "README.md").write_text("not source")
    assert [f.path for f in scan(tmp_path)] == ["src/app.ts"]


def test_large_files_are_skipped(tmp_path):
    (tmp_path / "big.ts").write_bytes(b"// x\n" * 300_000)
    assert scan(tmp_path) == []


def test_is_test_path():
    assert is_test_path("tests/tax.spec.ts")
    assert is_test_path("src/app/tax.service.spec.ts")
    assert is_test_path("src/__tests__/a.ts")
    assert is_test_path("Billing.Tests/TaxCalculatorTests.cs")
    assert is_test_path("src/Billing.UnitTests/Foo.cs")
    assert not is_test_path("src/billing/tax.ts")
    assert not is_test_path("Billing/TaxCalculator.cs")


def test_is_generated():
    assert is_generated("Foo.g.cs", b"")
    assert is_generated("Form1.Designer.cs", b"")
    assert is_generated("api.ts", b"// <auto-generated>\n")
    assert not is_generated("TaxCalculator.cs", b"namespace X;")
